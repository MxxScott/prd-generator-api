import { type PRDDocument, type ClientDiscoveryInput } from '../types/index.js';

export function generateMarkdownPRD(input: ClientDiscoveryInput, prd: PRDDocument): string {
  const date = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });

  let md = `# ${prd.title}\n\n`;
  
  md += `**Client:** ${input.clientName}\n`;
  md += `**Project:** ${input.projectName}\n`;
  md += `**Date Generated:** ${date}\n\n`;
  md += `---\n\n`;

  md += `## Executive Summary\n\n`;
  md += `${prd.executiveSummary}\n\n`;

  md += `## Target Audience & User Personas\n\n`;
  md += `**Primary Audience:** ${input.targetAudience}\n\n`;
  prd.userPersonas.forEach(persona => {
    md += `- ${persona}\n`;
  });
  md += `\n`;

  md += `## Feature Requirements\n\n`;
  prd.features.forEach(feature => {
    md += `### ${feature.featureName} [${feature.priority} Priority]\n\n`;
    md += `${feature.description}\n\n`;
  });

  md += `## Tech Stack Recommendations\n\n`;
  prd.techStackRecommendations.forEach(tech => {
    md += `- ${tech}\n`;
  });

  return md;
}

export function generateDesignDocMarkdown(doc: any): string {
  const colorList = doc.designSystem.colorPalette.map((c: string) => `- \`${c}\``).join('\n');
  
  const uiList = doc.uiComponents.map((c: any) => 
    `- **${c.componentName}**: ${c.purpose}`
  ).join('\n');

  const modelsList = doc.databaseModels.map((m: any) => {
    const fields = m.fields.map((f: string) => `  - \`${f}\``).join('\n');
    return `### ${m.modelName}\n${fields}`;
  }).join('\n\n');

  const apiTableRows = doc.apiEndpoints.map((api: any) => 
    `| **${api.method}** | \`${api.route}\` | ${api.description} |`
  ).join('\n');

  return `# ${doc.title}

## Architecture Overview
${doc.architectureOverview}

---

## Design System
### Color Palette
${colorList}

### Typography
${doc.designSystem.typography}

---

## Key UI Components
${uiList}

---

## Database Models
${modelsList}

---

## REST API Endpoints
| Method | Route | Description |
|---|---|---|
${apiTableRows}

---
*Generated by the Product Architect AI*
`;
}